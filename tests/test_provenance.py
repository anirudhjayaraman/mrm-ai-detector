import zipfile

from conftest import HUMAN_TEXT

from mrm_ai_detector.detector import Detector
from mrm_ai_detector.provenance import inspect_file, inspect_text

DOC_XML = (
    '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
    '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body>{}</w:body></w:document>'
)
CORE_XML = (
    '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
    '<cp:coreProperties xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties" '
    'xmlns:dc="http://purl.org/dc/elements/1.1/" xmlns:dcterms="http://purl.org/dc/terms/" '
    'xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance">'
    "<dc:creator>{creator}</dc:creator><dc:description>{desc}</dc:description>"
    '<dcterms:created xsi:type="dcterms:W3CDTF">{created}</dcterms:created></cp:coreProperties>'
)


def make_docx(path, text, creator="Jane Analyst", desc="", created="2024-03-01T10:00:00Z"):
    paras = "".join(f"<w:p><w:r><w:t>{p}</w:t></w:r></w:p>" for p in text.split("\n\n"))
    with zipfile.ZipFile(path, "w") as zf:
        zf.writestr("word/document.xml", DOC_XML.format(paras))
        zf.writestr("docProps/core.xml", CORE_XML.format(creator=creator, desc=desc, created=created))
    return path


def test_plain_human_text_has_no_hints():
    assert inspect_text(HUMAN_TEXT) == []


def test_chat_leftovers_are_reported():
    hints = [str(h) for h in inspect_text(
        "Certainly! Here's the revised finding:\n\nThe PRA expects tiering (https://example.org/ss1-23?utm_source=chatgpt.com). "
        ":contentReference[oaicite:2]{index=2}\nWould you like me to draft the remediation plan?"
    )]
    assert any("utm_source=chatgpt.com" in h for h in hints)
    assert any("citation markers" in h for h in hints)
    assert any("opener" in h for h in hints)
    assert any("assistant offer" in h for h in hints)


def test_ordinary_phrases_do_not_trigger():
    text = "As an AI model developer, we partner with banks. Let me know if you'd like the data. " * 3
    assert inspect_text(text) == []


def test_non_breaking_hyphens_need_volume():
    assert inspect_text("A piece‑wise hazard. " + HUMAN_TEXT) == []  # one stray character is not evidence
    dense = " ".join(["The k‑th‑to‑default spread uses a t‑copula."] * 10)
    assert any("non-breaking hyphen" in str(h) for h in inspect_text(dense))


def test_python_docx_metadata(tmp_path):
    gen = make_docx(tmp_path / "gen.docx", HUMAN_TEXT, creator="python-docx", desc="generated by python-docx",
                    created="2013-12-23T23:15:00Z")
    hints = [str(h) for h in inspect_file(gen)]
    assert any(h.startswith("[strong]") and "python-docx" in h for h in hints)
    assert any("2013-12-23" in h for h in hints)
    plain = make_docx(tmp_path / "plain.docx", HUMAN_TEXT)
    assert [str(h) for h in inspect_file(plain)] == []


def test_provenance_does_not_change_probability(tmp_path):
    det = Detector(bootstrap=0)
    gen = make_docx(tmp_path / "gen.docx", HUMAN_TEXT, creator="python-docx", desc="generated by python-docx")
    plain = make_docx(tmp_path / "plain.docx", HUMAN_TEXT)
    a, b = det.analyze_file(gen), det.analyze_file(plain)
    assert a.provenance and not b.provenance
    assert abs(a.probability - b.probability) < 1e-12


def test_text_input_gets_text_hints():
    r = Detector(bootstrap=0).analyze_text("Certainly! Here's the draft.\n\n" + HUMAN_TEXT)
    assert any("opener" in h for h in r.provenance)
